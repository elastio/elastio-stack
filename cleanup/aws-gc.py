class StringPattern:
    def __init__(self, pattern: str):
        self.values = pattern.strip().lower().split(",")

    def matches(self, suspect: str):
        suspect = suspect.lower()
        return any(value in suspect for value in self.values)


class DictPattern:
    def __init__(self, pattern: str):
        self.items = [
            DictPattern.parse_kv(item) for item in pattern.strip().lower().split(",")
        ]

    @staticmethod
    def parse_kv(item: str):
        parts = item.split("=", 1)
        return parts[0], None if len(parts) == 1 else parts[1]

    def matches(self, scrutinee: dict[str, str]):
        return any(
            (scrutinee_value := scrutinee.get(key)) is not None
            and (value is None or scrutinee_value == value)
            for key, value in self.items
        )


